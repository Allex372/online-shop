export const getCategoryByFilterValue = (filterValue) => {
  if (!filterValue) return null;
  const normalized = filterValue.toLowerCase().trim();
  return (
    CHEMISTRY_CATEGORIES.find(
      (c) => c.filterValue.toLowerCase().trim() === normalized
    ) || null
  );
};

